/**
 * Builds supabase/seed.sql from the deterministic catalog (the same generator the offline fake API
 * uses), so product p-0001 has the same name, price and images on both backends.
 *
 * Pure: takes the catalog in, returns the SQL text. `make-seed.ts` writes it to disk, and
 * tests/seedSql.test.ts checks the rows without a database.
 */
import { discountPercent, pickBestSellers } from '../../src/core/catalog/generate';
import type { Banner, Category, Product } from '../../src/core/catalog/types';
import { toCentimes } from '../../src/core/money';

/** SQL string literal. Doubling the quote is the only escape standard SQL strings need. */
export function sqlText(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlNullable(value: string | null): string {
  return value === null ? 'null' : sqlText(value);
}

function sqlTextArray(values: readonly string[]): string {
  return `array[${values.map(sqlText).join(', ')}]::text[]`;
}

export function categoryRow(category: Category, sort: number): string {
  return `(${[
    sqlText(category.id),
    sqlText(category.en),
    sqlText(category.ar),
    sqlText(category.icon),
    toCentimes(category.priceMin),
    toCentimes(category.priceMax),
    sort,
  ].join(', ')})`;
}

export function productRow(product: Product, bestSellerRank: number | null): string {
  return `(${[
    sqlText(product.id),
    sqlText(product.sku),
    sqlText(product.name),
    sqlText(product.nameAr),
    sqlText(product.brand),
    sqlText(product.brandAr),
    sqlText(product.category),
    toCentimes(product.price),
    product.oldPrice === null ? 'null' : toCentimes(product.oldPrice),
    discountPercent(product),
    product.rating.toFixed(1),
    product.reviews,
    product.inStock ? 'true' : 'false',
    sqlTextArray(product.images),
    sqlText(product.descriptionEn),
    sqlText(product.descriptionAr),
    sqlText(product.dominantColor),
    bestSellerRank === null ? 'null' : bestSellerRank,
  ].join(', ')})`;
}

export function bannerRow(banner: Banner, sort: number): string {
  return `(${[
    sqlText(banner.id),
    sqlText(banner.en.title),
    sqlText(banner.en.sub),
    sqlText(banner.en.cta),
    sqlText(banner.ar.title),
    sqlText(banner.ar.sub),
    sqlText(banner.ar.cta),
    sqlNullable(banner.category),
    sqlText(banner.tint),
    sort,
  ].join(', ')})`;
}

export interface SeedInput {
  categories: readonly Category[];
  products: readonly Product[];
  banners: readonly Banner[];
}

/** Rows per INSERT. Keeps each statement small enough for the dashboard's SQL editor. */
const CHUNK = 100;

export function buildSeedSql({ categories, products, banners }: SeedInput): string {
  const ranks = new Map(pickBestSellers(products).map((p, i) => [p.id, i + 1]));

  const out: string[] = [
    '-- GENERATED by `npm run supabase:seed` (scripts/supabase/make-seed.ts). Do not edit by hand.',
    `-- ${categories.length} categories, ${products.length} products, ${banners.length} banners.`,
    '-- Money is integer centimes, TVA included. Re-running replaces the whole catalog.',
    '',
    'begin;',
    '',
    // order_items references products, so a re-seed keeps existing orders by only touching the
    // catalog rows (upsert), never deleting products that an order points at.
    'insert into public.categories (id, name_en, name_ar, icon, price_min_h, price_max_h, sort) values',
    categories.map((c, i) => `  ${categoryRow(c, i)}`).join(',\n'),
    'on conflict (id) do update set name_en = excluded.name_en, name_ar = excluded.name_ar,',
    '  icon = excluded.icon, price_min_h = excluded.price_min_h, price_max_h = excluded.price_max_h,',
    '  sort = excluded.sort;',
    '',
    // best_seller_rank is unique: clear it first so a changed pick can't collide mid-upsert.
    'update public.products set best_seller_rank = null where best_seller_rank is not null;',
    '',
  ];

  for (let start = 0; start < products.length; start += CHUNK) {
    const chunk = products.slice(start, start + CHUNK);
    out.push(
      'insert into public.products (id, sku, name_en, name_ar, brand_en, brand_ar, category_id, price_h,',
      '  old_price_h, discount_pct, rating, reviews, in_stock, images, description_en, description_ar,',
      '  dominant_color, best_seller_rank) values',
      chunk.map((p) => `  ${productRow(p, ranks.get(p.id) ?? null)}`).join(',\n'),
      'on conflict (id) do update set sku = excluded.sku, name_en = excluded.name_en,',
      '  name_ar = excluded.name_ar, brand_en = excluded.brand_en, brand_ar = excluded.brand_ar,',
      '  category_id = excluded.category_id, price_h = excluded.price_h,',
      '  old_price_h = excluded.old_price_h, discount_pct = excluded.discount_pct,',
      '  rating = excluded.rating, reviews = excluded.reviews, in_stock = excluded.in_stock,',
      '  images = excluded.images, description_en = excluded.description_en,',
      '  description_ar = excluded.description_ar, dominant_color = excluded.dominant_color,',
      '  best_seller_rank = excluded.best_seller_rank;',
      '',
    );
  }

  out.push(
    'insert into public.banners (id, title_en, sub_en, cta_en, title_ar, sub_ar, cta_ar, category_id, tint, sort) values',
    banners.map((b, i) => `  ${bannerRow(b, i)}`).join(',\n'),
    'on conflict (id) do update set title_en = excluded.title_en, sub_en = excluded.sub_en,',
    '  cta_en = excluded.cta_en, title_ar = excluded.title_ar, sub_ar = excluded.sub_ar,',
    '  cta_ar = excluded.cta_ar, category_id = excluded.category_id, tint = excluded.tint,',
    '  sort = excluded.sort;',
    '',
    'commit;',
    '',
  );

  return out.join('\n');
}
